import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";

import { renderEditorHtml } from "../src/html-template.ts";

/**
 * Bundles the shared TipTap editor into the single HTML document the native
 * WebView loads. The output is committed so Metro can import it without a
 * build step; `src/webview-build.test.ts` fails if it drifts from the source.
 *
 *   pnpm --filter @withink/editor build:webview
 */

const here = path.dirname(fileURLToPath(import.meta.url));
const ENTRY = path.resolve(here, "../src/bridge-entry.ts");
const OUTPUT = path.resolve(
  here,
  "../../../apps/mobile/src/lib/editor-webview.generated.ts",
);

export async function buildEditorBundle() {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: ["chrome110", "safari16"],
    minify: true,
    // TipTap/ProseMirror are MIT; keep their notices in the shipped document.
    legalComments: "inline",
    logLevel: "silent",
    define: { "process.env.NODE_ENV": '"production"' },
  });
  const file = result.outputFiles?.[0];
  if (!file) throw new Error("esbuild produced no output.");
  return file.text;
}

export async function buildEditorHtml() {
  return renderEditorHtml(await buildEditorBundle());
}

export async function writeEditorHtml() {
  const html = await buildEditorHtml();
  const source = [
    "// @generated by packages/editor/scripts/build-webview.mjs — do not edit.",
    "// Regenerate with: pnpm --filter @withink/editor build:webview",
    `export const EDITOR_HTML = ${JSON.stringify(html)};`,
    "",
  ].join("\n");
  writeFileSync(OUTPUT, source, "utf8");
  return { bytes: Buffer.byteLength(html), path: OUTPUT };
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  const { bytes } = await writeEditorHtml();
  console.log(`editor WebView written (${Math.round(bytes / 1024)} KB)`);
}
